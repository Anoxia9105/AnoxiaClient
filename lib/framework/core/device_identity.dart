import 'package:anoxia/common/utils/sp_util.dart';
import 'package:flutter/foundation.dart';
import 'package:uuid/uuid.dart';

/// Stable installation-level identity shared by HTTP login, WebSocket and push.
/// A reinstall creates a new identity; account logout does not clear it.
class DeviceIdentity {
  DeviceIdentity._();

  static final DeviceIdentity instance = DeviceIdentity._();
  static const String _storageKey = 'client_device_uid';
  static const String _legacyPushStorageKey = 'push_device_uid';

  Future<String> getOrCreate() async {
    final current = SPUtil.instance.get(_storageKey);
    if (current != null && current.trim().isNotEmpty) return current.trim();

    // Reuse the UUID already generated by older mobile clients for push binding.
    final legacy = SPUtil.instance.get(_legacyPushStorageKey);
    final deviceUid = legacy != null && legacy.trim().isNotEmpty
        ? legacy.trim()
        : const Uuid().v4();
    await SPUtil.instance.set(_storageKey, deviceUid);
    await SPUtil.instance.set(_legacyPushStorageKey, deviceUid);
    return deviceUid;
  }

  Future<String> getPlatformQualifiedId() async {
    final platform = kIsWeb ? 'web' : defaultTargetPlatform.name.toLowerCase();
    return '$platform:${await getOrCreate()}';
  }
}
